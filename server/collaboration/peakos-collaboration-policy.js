'use strict';

const EVENT_REORDER_LIMIT = 500;
const EVENT_REORDER_BOUND = 1_000_000;

function policyResult(status, code, error) {
  return { ok: false, status, code, error };
}

function normalizeEventReorderItems(value) {
  if (!Array.isArray(value) || !value.length) {
    return policyResult(400, 'EVENT_REORDER_ITEMS_REQUIRED', '순서를 바꿀 할 일이 없습니다.');
  }
  if (value.length > EVENT_REORDER_LIMIT) {
    return policyResult(400, 'EVENT_REORDER_LIMIT_EXCEEDED', `한 번에 ${EVENT_REORDER_LIMIT}개까지만 정렬할 수 있습니다.`);
  }

  const seen = new Set();
  const items = [];
  for (const entry of value) {
    const id = String(entry?.id || '').trim();
    const sortOrder = Number(entry?.sortOrder);
    if (!id || id.length > 200 || id.includes('\0')) {
      return policyResult(400, 'EVENT_REORDER_ID_INVALID', '유효하지 않은 할 일 ID가 포함되어 있습니다.');
    }
    if (seen.has(id)) {
      return policyResult(400, 'EVENT_REORDER_ID_DUPLICATED', '같은 할 일이 두 번 포함되어 있습니다.');
    }
    if (!Number.isSafeInteger(sortOrder) || Math.abs(sortOrder) > EVENT_REORDER_BOUND) {
      return policyResult(400, 'EVENT_REORDER_SORT_INVALID', '할 일 순서 값이 올바르지 않습니다.');
    }
    const todoCat = entry?.todoCat === undefined
      ? undefined
      : String(entry.todoCat || '').trim().slice(0, 120) || null;
    seen.add(id);
    items.push({ id, sortOrder, todoCat });
  }
  return { ok: true, items };
}

function authorizeEventReorder({ items, rows, uid, role, externalCalendarOnly = false }) {
  const rowMap = new Map((Array.isArray(rows) ? rows : []).map(row => [String(row.id), row]));
  if (rowMap.size !== items.length || items.some(item => !rowMap.has(item.id))) {
    return policyResult(403, 'EVENT_REORDER_NOT_AUTHORIZED', '변경할 수 없는 할 일이 포함되어 있습니다.');
  }
  for (const item of items) {
    const row = rowMap.get(item.id);
    if (row.type !== 'todo') {
      return policyResult(400, 'EVENT_REORDER_TODO_ONLY', '할 일 항목만 순서를 바꿀 수 있습니다.');
    }
    if (externalCalendarOnly && row.is_internal_rule === true) {
      return policyResult(403, 'EVENT_REORDER_NOT_AUTHORIZED', '변경할 수 없는 할 일이 포함되어 있습니다.');
    }
    if (role !== 'admin' && String(row.owner_id || '') !== String(uid || '')) {
      return policyResult(403, 'EVENT_REORDER_NOT_AUTHORIZED', '본인이 만든 할 일만 순서를 바꿀 수 있습니다.');
    }
  }
  return { ok: true };
}

function normalizeChatMessageId(value) {
  const id = String(value ?? '').trim();
  // chat.id is a text UUID generated by PostgreSQL gen_random_uuid(). Keep the
  // accepted form aligned with stored identifiers instead of treating it as a
  // numeric sequence (which would reject every production message ID).
  if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(id)) return null;
  return id.toLowerCase();
}

module.exports = {
  EVENT_REORDER_LIMIT,
  authorizeEventReorder,
  normalizeChatMessageId,
  normalizeEventReorderItems,
};
